from __future__ import annotations

import argparse
import shutil
from pathlib import Path


def publish(source: Path, destination: Path) -> list[Path]:
    source, destination = source.resolve(), destination.resolve()
    if (
        source == destination
        or source in destination.parents
        or destination in source.parents
    ):
        raise ValueError("Generation staging and client paths must not overlap")
    for required in [
        "__init__.py",
        "api_client.py",
        "models/__init__.py",
        "api/__init__.py",
    ]:
        if not (source / required).is_file():
            raise ValueError(f"Incomplete generated client: missing {required}")
    obsolete = [
        path
        for path in destination.rglob("*.py")
        if not (source / path.relative_to(destination)).exists()
        and "Generated by OpenAPI Generator" in path.read_text()
    ]
    for path in obsolete:
        path.unlink()
    shutil.copytree(source, destination, dirs_exist_ok=True)
    return obsolete


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Publish staged client files and remove obsolete generated modules."
    )
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    args = parser.parse_args()
    obsolete = publish(args.source, args.destination)
    print(
        f"Published generated client; removed {len(obsolete)} obsolete generated modules"
    )


if __name__ == "__main__":
    main()
