from pathlib import Path

import pytest

from scripts.publish_generated_client import publish


def _generated(path: Path, value: str = "pass") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"# Generated by OpenAPI Generator\n{value}\n")


def _staging(path: Path) -> None:
    for name in [
        "__init__.py",
        "api_client.py",
        "models/__init__.py",
        "api/__init__.py",
    ]:
        _generated(path / name)


def test_clean_publication_removes_obsolete_exports_and_preserves_custom_code(tmp_path):
    stage, target = tmp_path / "stage", tmp_path / "target"
    _staging(stage)
    _generated(stage / "models/i_referee_config.py", "class IRefereeConfig: pass")
    _generated(
        target / "models/i_referee_config_model.py", "class IRefereeConfigModel: pass"
    )
    _generated(target / "api/obsolete_api.py")
    target.mkdir(exist_ok=True)
    (target / "lazy_model.py").write_text("custom support code")
    (target / "models/custom.py").write_text("custom model")
    removed = publish(stage, target)
    assert {path.name for path in removed} == {
        "i_referee_config_model.py",
        "obsolete_api.py",
    }
    assert not (target / "models/i_referee_config_model.py").exists()
    assert (target / "models/i_referee_config.py").read_text() == (
        stage / "models/i_referee_config.py"
    ).read_text()
    assert (target / "lazy_model.py").read_text() == "custom support code"
    assert (target / "models/custom.py").read_text() == "custom model"


def test_incomplete_generation_cannot_remove_current_client(tmp_path):
    stage, target = tmp_path / "stage", tmp_path / "target"
    _generated(target / "models/old.py")
    stage.mkdir()
    with pytest.raises(ValueError, match="Incomplete"):
        publish(stage, target)
    assert (target / "models/old.py").exists()


def test_staging_cannot_overlap_current_client(tmp_path):
    with pytest.raises(ValueError, match="overlap"):
        publish(tmp_path, tmp_path / "nested")
